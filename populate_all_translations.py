def populate_database():
    """Populate MongoDB with all translations"""
    from dotenv import load_dotenv
    import os
    
    load_dotenv()
    
    app = Flask(__name__)
    app.config['MONGO_URI'] = os.getenv('MONGODB_URI') + os.getenv('DATABASE_NAME', 'vaanimitra_db')
    mongo.init_app(app)
    
    with app.app_context():
        logger.info("Starting database population...")
        
        # Clear existing translations
        result = mongo.db.translations.delete_many({})
        logger.info(f"Cleared {result.deleted_count} existing translations")
        
        total_inserted = 0
        
        # Insert all translations
        for language, words in TRANSLATIONS.items():
            logger.info(f"Processing {language}...")
            
            for english_word, translated_word in words.items():
                translation_doc = {
                    'english': english_word.lower(),
                    'language': language.lower(),
                    'translation': translated_word,
                    'verified': True,
                    'created_at': datetime.utcnow(),
                    'updated_at': datetime.utcnow()
                }
                
                try:
                    mongo.db.translations.insert_one(translation_doc)
                    total_inserted += 1
                except Exception as e:
                    logger.error(f"Error inserting {english_word} -> {translated_word}: {e}")
            
            logger.info(f"Completed {language}: inserted {len(words)} translations")
        
        # Create indexes for faster lookups
        logger.info("Creating indexes...")
        mongo.db.translations.create_index([('english', 1), ('language', 1)], unique=True)
        mongo.db.translations.create_index([('language', 1)])
        
        logger.info(f"✓ Database population complete! Total translations inserted: {total_inserted}")
        logger.info(f"Languages covered: {len(TRANSLATIONS)}")
        logger.info(f"Words per language: ~{total_inserted // len(TRANSLATIONS)}")

if __name__ == "__main__":
    populate_database()
